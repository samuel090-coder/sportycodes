import { createRoot } from "react-dom/client";
import App from "./App.tsx";
import "./index.css";
import { supabase } from "@/integrations/supabase/client";

// Keep Realtime authenticated so postgres_changes subscriptions receive
// events immediately after login (without requiring a browser refresh).
supabase.auth.getSession().then(({ data }) => {
  if (data.session?.access_token) {
    supabase.realtime.setAuth(data.session.access_token);
  }
});
supabase.auth.onAuthStateChange((_event, session) => {
  if (session?.access_token) {
    supabase.realtime.setAuth(session.access_token);
  }
});


// Register push service worker on app startup (works everywhere)
if ("serviceWorker" in navigator) {
  navigator.serviceWorker
    .register("/sw.js", { updateViaCache: "none" })
    .then((registration) => {
      console.log("Service Worker registered on startup:", registration);
      // Proactively check for updates (important after SW strategy changes)
      registration.update().catch(() => {});
    })
    .catch((error) => {
      console.error("Service Worker registration failed:", error);
    });
}

// Offline / caching service worker (generated by vite-plugin-pwa).
// Never register it in dev, in an iframe, or in Lovable preview hosts.
const canUseOfflineSW = () => {
  if (!import.meta.env.PROD) return false;
  if (window.top !== window.self) return false;
  const h = window.location.hostname;
  if (h.startsWith("id-preview--") || h.startsWith("preview--")) return false;
  if (h === "lovableproject.com" || h.endsWith(".lovableproject.com")) return false;
  if (h === "lovableproject-dev.com" || h.endsWith(".lovableproject-dev.com")) return false;
  if (h === "beta.lovable.dev" || h.endsWith(".beta.lovable.dev")) return false;
  if (new URL(window.location.href).searchParams.get("sw") === "off") return false;
  return true;
};

if ("serviceWorker" in navigator) {
  if (canUseOfflineSW()) {
    window.addEventListener("load", () => {
      navigator.serviceWorker
        .register("/pwa-sw.js", { updateViaCache: "none" })
        .catch((e) => console.warn("Offline SW registration skipped:", e));
    });
  } else {
    navigator.serviceWorker.getRegistrations().then((regs) => {
      regs
        .filter((r) => r.active?.scriptURL.includes("/pwa-sw.js"))
        .forEach((r) => r.unregister());
    });
  }
}

createRoot(document.getElementById("root")!).render(<App />);
